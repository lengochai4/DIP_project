    def add(key, category, label, symbols, positions, bonds):
        # Validate immediately
        assert len(symbols) == len(positions), f"{key}: symbols ({len(symbols)}) != positions ({len(positions)})"
        pos = np.asarray(positions, dtype=float)
        assert pos.shape == (len(symbols), 3), f"{key}: pos shape {pos.shape}"
        assert np.all(np.isfinite(pos)), f"{key}: pos not finite"
        # Check connected
        adj = [[] for _ in symbols]
        seen_bonds = set()
        for a, b, order in bonds:
            assert 0 <= a < len(symbols) and 0 <= b < len(symbols) and a != b, f"{key}: bad bond indices {a}, {b}"
            assert order in (1, 2, 3), f"{key}: bad order {order}"
            pair = tuple(sorted((a, b)))
            assert pair not in seen_bonds, f"{key}: duplicate bond {pair}"
            seen_bonds.add(pair)
            adj[a].append(b)
            adj[b].append(a)
        
        visited = set()
        queue = [0]
        while queue:
            curr = queue.pop(0)
            if curr not in visited:
                visited.add(curr)
                queue.extend(n for n in adj[curr] if n not in visited)
        assert len(visited) == len(symbols), f"{key}: Disconnected graph! {len(visited)}/{len(symbols)} connected"

        compounds[key] = {
            "category": category,
            "label": label,
            "symbols": symbols,
            "positions": [[round(float(c), 4) for c in p] for p in pos],
            "bonds": bonds
        }

